"""Download COCO val2017 + KITTI (Ultralytics release) and build COCO-format GT files for KITTI.

Outputs
  data/coco/val2017/*.jpg, data/coco/annotations/instances_val2017.json
  data/kitti/images/{train,val}, data/kitti/labels/{train,val}       (YOLO txt labels)
  data/kitti/annotations/kitti_val_native.json   7 KITTI classes, COCO json format
  data/kitti/annotations/kitti_val_cocomap.json  KITTI GT re-labelled into COCO ids (+ ignore regions)
  configs/kitti_local.yaml                       absolute-path dataset yaml for Ultralytics training
  results/dataset_stats.json                     counts per class / scale (goes in the report)

Usage
  python scripts/prepare_data.py              # full
  python scripts/prepare_data.py --quick      # COCO: annotations + first N images only
"""
from __future__ import annotations

import argparse
import urllib.request
import zipfile
from collections import Counter
from pathlib import Path

from common import RESULTS, load_cfg, log_event, p, save_json, load_json

COCO_IMG_ZIP = "http://images.cocodataset.org/zips/val2017.zip"
COCO_ANN_ZIP = "http://images.cocodataset.org/annotations/annotations_trainval2017.zip"
COCO_IMG_URL = "http://images.cocodataset.org/val2017/{}"
KITTI_ZIP = "https://github.com/ultralytics/assets/releases/download/v0.0.0/kitti.zip"


def download(url: str, dst: Path) -> Path:
    """Download with a progress bar (uses Ultralytics' robust downloader, retries included)."""
    from ultralytics.utils.downloads import safe_download
    dst.parent.mkdir(parents=True, exist_ok=True)
    if dst.exists() and dst.stat().st_size > 0:
        print(f"[skip] {dst.name} already downloaded")
        return dst
    safe_download(url=url, file=dst, unzip=False)
    return dst


def extract(zip_path: Path, out_dir: Path) -> None:
    print(f"[unzip] {zip_path.name} -> {out_dir}")
    out_dir.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(zip_path) as z:
        z.extractall(out_dir)


# ----------------------------------------------------------------------------- COCO
def prepare_coco(cfg: dict, quick: bool, n_quick: int) -> None:
    coco_root = p("data/coco")
    ann = p(cfg["datasets"]["coco"]["gt"])
    img_dir = p(cfg["datasets"]["coco"]["images"])
    if not ann.exists():
        z = download(COCO_ANN_ZIP, coco_root / "annotations_trainval2017.zip")
        extract(z, coco_root)
    n_have = len(list(img_dir.glob("*.jpg"))) if img_dir.exists() else 0
    if quick:
        gt = load_json(ann)
        imgs = sorted(gt["images"], key=lambda r: r["id"])[:n_quick]
        img_dir.mkdir(parents=True, exist_ok=True)
        for r in imgs:
            f = img_dir / r["file_name"]
            if not f.exists():
                urllib.request.urlretrieve(COCO_IMG_URL.format(r["file_name"]), f)
        print(f"[coco] quick mode: {len(imgs)} images")
    elif n_have < 5000:
        z = download(COCO_IMG_ZIP, coco_root / "val2017.zip")
        extract(z, coco_root)
    print(f"[coco] images: {len(list(img_dir.glob('*.jpg')))}")


# ----------------------------------------------------------------------------- KITTI
def prepare_kitti(cfg: dict) -> None:
    kroot = p("data/kitti")
    if not (kroot / "images" / "val").exists():
        z = download(KITTI_ZIP, p("data/kitti.zip"))
        extract(z, kroot)            # zip has images/, labels/, kitti.yaml at top level
    build_kitti_gt(cfg)
    # Absolute-path yaml so Ultralytics never guesses a datasets_dir
    names = cfg["taxonomy"]["kitti_classes"]
    yaml_txt = (f"# generated by scripts/prepare_data.py\npath: {kroot.as_posix()}\n"
                "train: images/train\nval: images/val\nnames:\n"
                + "".join(f"  {i}: {n}\n" for i, n in enumerate(names)))
    out = p(cfg["datasets"]["kitti"]["yolo_yaml"])
    out.write_text(yaml_txt, encoding="utf-8")
    print(f"[kitti] wrote {out}")


def read_yolo_labels(txt: Path, w: int, h: int):
    """YOLO txt rows 'cls cx cy bw bh' (normalised) -> list of (cls, [x, y, bw, bh]) in pixels."""
    rows = []
    if not txt.exists():
        return rows
    for line in txt.read_text().splitlines():
        parts = line.split()
        if len(parts) != 5:
            continue
        c, cx, cy, bw, bh = int(parts[0]), *map(float, parts[1:])
        bw_px, bh_px = bw * w, bh * h
        x = cx * w - bw_px / 2
        y = cy * h - bh_px / 2
        rows.append((c, [round(x, 2), round(y, 2), round(bw_px, 2), round(bh_px, 2)]))
    return rows


def scale_bucket(area: float) -> str:
    return "small" if area < 32 ** 2 else "medium" if area < 96 ** 2 else "large"


def build_kitti_gt(cfg: dict) -> None:
    from PIL import Image
    tax = cfg["taxonomy"]
    names = tax["kitti_classes"]
    native_keep = tax["native_eval_classes"]
    kroot = p("data/kitti")
    img_dir = kroot / "images" / "val"
    lbl_dir = kroot / "labels" / "val"

    images, native_anns, mapped_anns = [], [], []
    stats = {"native": Counter(), "native_scale": Counter(), "cocomap": Counter(),
             "cocomap_ignored": Counter()}
    files = sorted(img_dir.glob("*.png"))
    for img_id, f in enumerate(files, start=1):
        w, h = Image.open(f).size
        images.append({"id": img_id, "file_name": f.name, "width": w, "height": h})
        for c, box in read_yolo_labels(lbl_dir / (f.stem + ".txt"), w, h):
            name = names[c]
            area = round(box[2] * box[3], 2)
            if name in native_keep:
                native_anns.append({"id": len(native_anns) + 1, "image_id": img_id,
                                    "category_id": native_keep.index(name) + 1, "bbox": box,
                                    "area": area, "iscrowd": 0})
                stats["native"][name] += 1
                stats["native_scale"][f"{name}/{scale_bucket(area)}"] += 1
            m = tax["to_coco"].get(name)
            if m is not None:
                mapped_anns.append({"id": len(mapped_anns) + 1, "image_id": img_id,
                                    "category_id": m["coco_id"], "bbox": box, "area": area,
                                    "iscrowd": int(m["ignore"])})
                key = f"{name}->{m['coco_name']}"
                (stats["cocomap_ignored"] if m["ignore"] else stats["cocomap"])[key] += 1

    out_dir = kroot / "annotations"
    native = {"info": {"description": "KITTI val (Ultralytics split), native classes"},
              "images": images, "annotations": native_anns,
              "categories": [{"id": i + 1, "name": n} for i, n in enumerate(native_keep)]}
    cocomap = {"info": {"description": "KITTI val mapped to COCO ids; iscrowd=1 = ignore region"},
               "images": images, "annotations": mapped_anns,
               "categories": [{"id": 1, "name": "person"}, {"id": 3, "name": "car"},
                              {"id": 8, "name": "truck"}]}
    save_json(native, out_dir / "kitti_val_native.json", indent=None)
    save_json(cocomap, out_dir / "kitti_val_cocomap.json", indent=None)
    s = {k: dict(sorted(v.items())) for k, v in stats.items()}
    s["n_val_images"] = len(images)
    s["n_train_images"] = len(list((kroot / "images" / "train").glob("*.png")))
    save_json(s, RESULTS / "dataset_stats.json")
    print(f"[kitti] val images={len(images)} native boxes={len(native_anns)} "
          f"cocomap boxes={len(mapped_anns)}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true")
    ap.add_argument("--only", choices=["coco", "kitti"], default=None)
    args = ap.parse_args()
    cfg = load_cfg()
    n_quick = cfg["quick"]["n_images"]
    if args.only in (None, "kitti"):
        prepare_kitti(cfg)
    if args.only in (None, "coco"):
        prepare_coco(cfg, args.quick, n_quick)
    log_event("prepare_data", quick=args.quick, only=args.only)


if __name__ == "__main__":
    main()
